"""Predeclared near-boundary realizability audit for the 35-moment FP map.

The audit answers the three concrete questions raised after Stage 52:

* what happens as a positive crossing-jet family approaches the H2 boundary;
* which part of the update (diffusion, collision, transport, or splitting)
  first loses a necessary moment-matrix condition; and
* whether the answer is stable under a factor-two time refinement.

H2 and H4 are the normalized moment matrices generated by monomials through
degree one and two, respectively.  H2 uses moments through degree two; H4
uses every retained moment through degree four.  Nonnegative eigenvalues are
necessary for a positive velocity distribution.  They are not a proof of
full realizability.
"""

