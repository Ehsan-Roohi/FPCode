def run_campaign(
    mode: str, output: Path, epsilon_index: int | None = None
) -> dict[str, object]:
    config = (
        configuration(mode)
        if epsilon_index is None
        else configuration_for_epsilon(mode, epsilon_index)
    )
    output.mkdir(parents=True, exist_ok=True)
    manifest = _manifest(config, mode, epsilon_index)
    (output / "stage53_manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    )
    histories: list[dict[str, object]] = []
    for epsilon, method, dt in product(
        config.epsilons, METHODS, (config.coarse_dt, config.fine_dt)
    ):
        print(
            f"[stage53] epsilon={epsilon:g} method={method} dt={dt:g}",
            flush=True,
        )
        histories.append(run_history(method, epsilon, dt, config))
    summary = _summary(config, histories)
    _write_history_csv(output / "stage53_histories.csv", histories)
    serializable_summary = json.loads(
        json.dumps(summary, allow_nan=True)
    )
    (output / "stage53_summary.json").write_text(
        json.dumps(serializable_summary, indent=2, sort_keys=True) + "\n"
    )
    _write_figures(output, config, histories)
    _write_report(output, summary, manifest)
    print(
        f"[stage53] completed status={summary['overall_status']} output={output}",
        flush=True,
    )
    return summary


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("smoke", "unity"), default="smoke")
    parser.add_argument(
        "--output",
        type=Path,
        default=REPOSITORY_ROOT / "results" / "riemann35_stage53",
    )
    parser.add_argument(
        "--epsilon-index",
        type=int,
        default=None,
        help="run only the indexed locked epsilon case (Unity array tasks use 0..4)",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    run_campaign(args.mode, args.output, args.epsilon_index)


if __name__ == "__main__":
    main()
